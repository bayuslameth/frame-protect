alg_content = """
# DCT Watermarking Algorithm

## Overview
The digital watermarking system utilizes the Discrete Cosine Transform (DCT) to embed a binary payload into the frequency domain of an image.

## Embedding Workflow
1. **Preprocessing**: The original RGB image is converted to the YCbCr color space. Only the Luminance (Y) channel is selected for processing.
2. **Block Division**: The Y channel is divided into non-overlapping 8×8 pixel blocks.
3. **Level Shifting**: Pixel values in each block are level-shifted by subtracting 128.0 to center the data around zero.
4. **DCT Transform**: The 2D DCT-II is applied using matrix multiplication ($D = C \cdot B \cdot C^T$) where $C$ is the standard DCT-II coefficient matrix.
5. **Secret-Key Permutation**: The payload bits are mapped to a deterministic subset of blocks. The random permutation is generated by seeding the NumPy PRNG with a 32-bit integer derived from the SHA-256 hash of the secret key.
6. **Coefficient Selection**: For each selected block, two mid-frequency coefficients are chosen (e.g., $U_1, V_1 = (4,5)$ and $U_2, V_2 = (5,4)$).
7. **Watermark Embedding**: A margin-based rule is applied to the magnitudes of the chosen coefficients. If bit `1` is to be embedded, coefficient A is made larger than coefficient B by a specific margin. If `0`, the reverse is applied. Signs are preserved.
8. **IDCT Transform**: The 2D IDCT is applied to convert the block back to the spatial domain.
9. **Reconstruction**: The block is reverse-level-shifted (add 128.0) and clipped to [0, 255].
10. **Image Assembly**: The watermarked Y channel is merged back with Cb and Cr, and converted to RGB.

## Extraction Workflow
1. **Key Derivation**: The exact same block indices are generated using the secret key seed.
2. **Extraction**: The 8x8 block is transformed via DCT. The magnitudes of the selected mid-frequency coefficients are compared to extract the embedded binary bit.
"""
write_md(os.path.join(docs_dir, "ALGORITHM.md"), alg_content)

